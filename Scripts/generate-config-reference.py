#!/usr/bin/env python3
"""
Generates docs/configuration-reference.md - every configuration key the framework reads, found by
scanning src/main/java, so the reference cannot drift from the code.

A "key" is a string literal passed to:
    ConfigReader.get / getNonBlank / getInt / getBoolean ("key" [, default])
    System.getProperty / Boolean.getBoolean / Integer.getInteger / Long.getLong ("key" [, default])
Each key can be set as  -Dkey=value  on the Maven command line, or as `key=value` in
src/test/resources/config/global.properties or <site>.properties (ConfigReader layers them).
Plain JVM keys (os.*, java.*, user.*) are skipped.

Usage:
    python3 Scripts/generate-config-reference.py            # (re)write docs/configuration-reference.md
    python3 Scripts/generate-config-reference.py --check    # exit 1 if the file is out of date (CI/audit)

Dependency-free (Python stdlib only), deterministic output (no timestamps) so --check is reliable.
"""
import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_ROOTS = [ROOT / "src" / "main" / "java", ROOT / "src" / "test" / "java"]  # core/mock, core/api etc. live under src/test/java
CONFIG_DIR = ROOT / "src" / "test" / "resources" / "config"
OUT = ROOT / "docs" / "configuration-reference.md"

CALL = re.compile(
    r'\b(ConfigReader\.(?:get|getNonBlank|getInt|getBoolean)'
    r'|System\.getProperty|Boolean\.getBoolean|Integer\.getInteger|Long\.getLong)'
    r'\(\s*"([A-Za-z0-9][A-Za-z0-9_.\-]*)"\s*(?:,\s*([^,()]+?|"[^"]*"))?\s*\)'
)
JVM_PREFIXES = ("os.", "java.", "user.", "file.", "line.", "path.", "sun.", "awt.")
JVM_EXACT = {"os.name", "user.dir", "user.home", "java.version"}


def scan():
    """key -> {"defaults": set, "files": set, "via": set}"""
    found = defaultdict(lambda: {"defaults": set(), "files": set(), "via": set()})
    files = [(root, p) for root in SRC_ROOTS if root.is_dir() for p in sorted(root.rglob("*.java"))]
    for root, path in files:
        if path.name.endswith("Test.java"):
            continue  # unit tests set fake values for keys; they are not where a key is defined or used
        text = path.read_text(encoding="utf-8", errors="replace")
        rel = path.relative_to(root).as_posix().replace("/", ".")[: -len(".java")]
        rel = rel.replace("com.automation.", "", 1)
        for m in CALL.finditer(text):
            accessor, key, default = m.group(1), m.group(2), m.group(3)
            if key in JVM_EXACT or key.startswith(JVM_PREFIXES):
                continue
            entry = found[key]
            entry["files"].add(rel)
            entry["via"].add("-D / config" if accessor.startswith("ConfigReader") else "-D")
            if default is not None:
                default = default.strip()
                if re.fullmatch(r'"[^"]*"|-?\d+(\.\d+)?[LlFfDd]?|true|false|null', default):
                    entry["defaults"].add(default.strip('"') if default.startswith('"') else default)
    return found


def config_sources():
    """(display name, text) per site/global config file, identical on a dev machine and on CI.

    Some config files are gitignored because they hold device-specific values (mobile.properties) and
    only a committed `<name>.properties.example` exists on a fresh checkout. When an .example exists
    it is the source of truth, so the generated page never differs between a developer's machine
    (which also has the real file) and CI (which does not). _TEMPLATE is a scaffold, not a config.
    """
    sources = {}
    if not CONFIG_DIR.is_dir():
        return []
    for p in sorted(CONFIG_DIR.glob("*.properties")):
        sources[p.name] = p
    for p in sorted(CONFIG_DIR.glob("*.properties.example")):
        sources[p.name[: -len(".example")]] = p  # overrides the real file of the same name
    return [(name, path.read_text(encoding="utf-8", errors="replace"))
            for name, path in sorted(sources.items()) if not name.startswith("_")]


_SOURCES = None


def files_defining(key):
    global _SOURCES
    if _SOURCES is None:
        _SOURCES = config_sources()
    pattern = re.compile(rf"^\s*{re.escape(key)}\s*=", re.M)
    return [name for name, text in _SOURCES if pattern.search(text)]


def group_of(key):
    return key.split(".")[0] if "." in key else "(general)"


def render(found):
    groups = defaultdict(list)
    for key in sorted(found):
        groups[group_of(key)].append(key)

    out = []
    out.append("# Configuration reference\n")
    out.append("<!-- GENERATED by Scripts/generate-config-reference.py - do not edit by hand. "
               "Regenerate with: python3 Scripts/generate-config-reference.py -->\n")
    out.append(f"{len(found)} keys read by the framework code. Set any of them as `-Dkey=value` on the Maven "
               "command line (highest priority), or as `key=value` in `src/test/resources/config/global.properties` "
               "(all sites) or `<site>.properties` (one site). Keys read only through `System.getProperty` "
               "are JVM `-D` flags only. \"Default\" is the fallback written in the code; a blank means the code "
               "has no literal default (the feature is off, or the key is required where it is used).\n")
    out.append("The ordinary run flags (`-Dsite`, `-Dbrowser`, `-Dheadless`, `-DsuiteXmlFile`, ...) are in "
               "[ALL_COMMANDS.md](../ALL_COMMANDS.md); this page is the complete key list.\n")
    out.append("## Groups\n")
    for g in sorted(groups):
        out.append(f"- [`{g}`](#{re.sub(r'[^a-z0-9]+', '-', g.lower()).strip('-')}) - {len(groups[g])} key(s)")
    out.append("")
    for g in sorted(groups):
        out.append(f"## {g}\n")
        out.append("| Key | Default | Set via | Defined in config files | Read in |")
        out.append("|---|---|---|---|---|")
        for key in groups[g]:
            e = found[key]
            defaults = ", ".join(f"`{d}`" for d in sorted(e["defaults"]) if d != "")
            via = " / ".join(sorted(e["via"]))
            cfg = ", ".join(f"`{n}`" for n in files_defining(key)) or ""
            readers = sorted(e["files"])
            shown = ", ".join(f"`{r}`" for r in readers[:3]) + (f" +{len(readers) - 3} more" if len(readers) > 3 else "")
            out.append(f"| `{key}` | {defaults} | {via} | {cfg} | {shown} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if docs/configuration-reference.md is out of date")
    args = ap.parse_args(argv)

    content = render(scan())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print(f"  ✗ {OUT.relative_to(ROOT)} is out of date - run: python3 Scripts/generate-config-reference.py")
            return 1
        print(f"  ✓ {OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
