"""UI spec -> keyword-driven scenario files (script CSV + object repository + suite XML).

Written into the run's own workspace; the generic com.automation.core.wizard.WizardKeywordRunTest
replays them through the normal KeywordEngine.  Locators are deduplicated into an object
repository (wiz.e1, wiz.e2, ...) so the script's locatorKey column stays the framework's own format.
"""
import csv
import io
import os
import re
from xml.sax.saxutils import quoteattr

from specs.converters import common


def case_name(scenario_name):
    safe = re.sub(r"[^A-Za-z0-9]+", "_", scenario_name).strip("_")
    return "TC_" + (safe or "scenario")


def convert(spec, inputs_dir):
    d, t = spec["details"], spec["target"]
    collect = common.new_collect()
    repo, rows, keys = {}, [], {}

    for i, step in enumerate(d["steps"], 1):
        loc = (step.get("locator") or "").strip()
        key = ""
        if loc:
            if loc not in keys:
                keys[loc] = f"wiz.e{len(keys) + 1}"
                repo[keys[loc]] = loc
            key = keys[loc]
        rows.append([case_name(d["scenarioName"]), i, step["keyword"], key,
                     common.rewrite_refs(step.get("data") or "", collect),
                     common.rewrite_refs(step.get("expected") or "", collect),
                     (step.get("description") or "").strip()])

    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["testCase", "stepNo", "keyword", "locatorKey", "testData", "expected", "description"])
    w.writerows(rows)
    script = common.write_text(os.path.join(inputs_dir, "scenario.csv"), buf.getvalue())

    repo_text = "# generated by the dashboard test wizard\n" + "".join(
        f"{k}={common.props_escape(v)}\n" for k, v in repo.items())
    repo_path = common.write_text(os.path.join(inputs_dir, "objectrepository.properties"), repo_text)

    suite_name = quoteattr("Wizard - " + spec["name"])
    suite = (
        '<!DOCTYPE suite SYSTEM "https://testng.org/testng-1.0.dtd">\n'
        f'<suite name={suite_name} parallel="none" thread-count="1">\n'
        '  <listeners>\n    <listener class-name="com.automation.sites.listeners.RetryListener"/>\n  </listeners>\n'
        f'  <test name={suite_name} preserve-order="true">\n'
        '    <groups><run><include name="wizard"/></run></groups>\n'
        '    <classes><class name="com.automation.core.wizard.WizardKeywordRunTest"/></classes>\n'
        '  </test>\n</suite>\n')
    suite_path = common.write_text(os.path.join(inputs_dir, "suite.xml"), suite)

    props = {"site": t["site"], "browser": t.get("browser", "chrome"),
             "headless": "true" if t.get("headless", True) else "false",
             "retry.count": str(t.get("retryCount", 0)),
             "wizard.keyword.repo": repo_path, "wizard.keyword.script": script,
             "wizard.keyword.cases": case_name(d["scenarioName"])}
    if t.get("baseUrl"):
        props["url"] = t["baseUrl"]
    return {"files": [script, repo_path, suite_path], "suite_xml": suite_path, "properties": props,
            "secret_env": collect["secrets"], "env_passthrough": sorted(collect["env"])}
