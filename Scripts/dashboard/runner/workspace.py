"""One isolated folder per run under <data>/runs/<run-id>/, plus the cleanup rules.

What a run folder holds: spec.json, inputs/ (generated scripts), properties.generated,
status.json, run.log, report/ (snapshot of the report folders), report-link.txt.
(Maven itself still writes into the repo's target/ — runs share that, which is why the queue
defaults to ONE run at a time; see queue.py.)
"""
import json
import os
import re
import secrets
import shutil
import tempfile
import time
from datetime import datetime, timezone

from specs import spec_store

RUN_ID_RE = re.compile(r"^\d{8}-\d{6}-[0-9a-f]{6}$")
KEEP_LAST = 30
KEEP_DAYS = 14
MAX_REPORT_COPY_MB = 200


def runs_dir():
    return os.path.join(spec_store.data_dir(), "runs")


def new_run_id():
    return datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S-") + secrets.token_hex(3)


def path_for(run_id):
    if not RUN_ID_RE.match(run_id or ""):
        raise ValueError("invalid run id")
    return os.path.join(runs_dir(), run_id)


def create(run_id, spec):
    d = path_for(run_id)
    os.makedirs(os.path.join(d, "inputs"), exist_ok=False)
    write_json(os.path.join(d, "spec.json"), spec)
    return d


def write_json(path, obj):
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), suffix=".tmp")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2)
        f.write("\n")
    os.replace(tmp, path)


def read_status(run_id):
    with open(os.path.join(path_for(run_id), "status.json"), encoding="utf-8") as f:
        return json.load(f)


def write_status(run_id, **fields):
    d = path_for(run_id)
    p = os.path.join(d, "status.json")
    cur = {}
    if os.path.isfile(p):
        with open(p, encoding="utf-8") as f:
            cur = json.load(f)
    cur.update(fields)
    write_json(p, cur)
    return cur


def list_runs(limit=50):
    root = runs_dir()
    if not os.path.isdir(root):
        return []
    out = []
    for rid in sorted(os.listdir(root), reverse=True)[:limit]:
        if RUN_ID_RE.match(rid):
            try:
                out.append(read_status(rid))
            except (OSError, ValueError):
                continue
    return out


def write_properties_generated(run_id, properties):
    """The -D properties of the run (secrets never appear: they're env vars, not properties)."""
    lines = "".join(f"{k}={v}\n" for k, v in sorted(properties.items()))
    p = os.path.join(path_for(run_id), "properties.generated")
    with open(p, "w", encoding="utf-8") as f:
        f.write("# generated by the dashboard test wizard — passed to the test process as -Dkey=value\n" + lines)


def snapshot_reports(run_id, repo_root, rel_dirs):
    """Copy the chosen report folders into <run>/report/. Skips anything over the size cap."""
    copied = []
    for rel in rel_dirs:
        src = os.path.join(repo_root, rel)
        if not os.path.isdir(src):
            continue
        size = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(src) for f in fs)
        if size > MAX_REPORT_COPY_MB * 1024 * 1024:
            continue
        dest = os.path.join(path_for(run_id), "report", os.path.basename(rel))
        shutil.rmtree(dest, ignore_errors=True)
        shutil.copytree(src, dest)
        copied.append(os.path.basename(rel))
    return copied


def cleanup(active_ids=()):
    """Delete runs beyond KEEP_LAST or older than KEEP_DAYS. Never touches an active run."""
    root = runs_dir()
    if not os.path.isdir(root):
        return []
    ids = sorted((r for r in os.listdir(root) if RUN_ID_RE.match(r)), reverse=True)
    cutoff = time.time() - KEEP_DAYS * 86400
    removed = []
    for i, rid in enumerate(ids):
        if rid in active_ids:
            continue
        d = os.path.join(root, rid)
        if i >= KEEP_LAST or os.path.getmtime(d) < cutoff:
            shutil.rmtree(d, ignore_errors=True)
            removed.append(rid)
    return removed
