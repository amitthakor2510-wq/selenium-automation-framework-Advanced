package com.automation.core.recorder;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Creates, once per site, the tiny TestNG class and suite file that run every recorded test case,
 * so a new recording needs no hand-written Java: the class discovers the test cases in the site's
 * recorded script on its own. Nothing is created if the site has no test package yet, and existing
 * files are never touched.
 */
public final class RunnerScaffold {

    private RunnerScaffold() {
    }

    /** Names the generated test class for a site, e.g. {@code RecordedSaucedemoKeywordTest}. */
    public static String className(String site) {
        return "Recorded" + site.substring(0, 1).toUpperCase(Locale.ROOT) + site.substring(1).toLowerCase(Locale.ROOT)
            + "KeywordTest";
    }

    /**
     * @param projectRoot    project directory
     * @param site           site name as used for -Dsite
     * @param objectRepoName classpath resource of the object repository, e.g. {@code objectrepository/saucedemo.properties}
     * @param scriptPath     project-relative path of the recorded keyword CSV
     * @return the files that were created (empty if they already existed or the site has no test package)
     */
    public static List<Path> ensure(Path projectRoot, String site, String objectRepoName, String scriptPath) throws IOException {
        List<Path> created = new ArrayList<>();
        String pkg = site.toLowerCase(Locale.ROOT);
        Path packageDir = projectRoot.resolve("src/test/java/com/automation/sites").resolve(pkg).resolve("tests");
        if (!Files.isDirectory(packageDir)) {
            return created;
        }
        String className = className(site);
        Path classFile = packageDir.resolve(className + ".java");
        if (!Files.exists(classFile)) {
            Files.writeString(classFile, classSource(pkg, className, objectRepoName, scriptPath), StandardCharsets.UTF_8);
            created.add(classFile);
        }
        Path suitesDir = projectRoot.resolve("testng-suites");
        Path suiteFile = suitesDir.resolve(site + "-recorded.xml");
        if (Files.isDirectory(suitesDir) && !Files.exists(suiteFile)) {
            Files.writeString(suiteFile, suiteSource(site, pkg, className), StandardCharsets.UTF_8);
            created.add(suiteFile);
        }
        return created;
    }

    static String classSource(String pkg, String className, String objectRepoName, String scriptPath) {
        return "package com.automation.sites." + pkg + ".tests;\n\n"
            + "import com.automation.sites.core.KeywordScriptSuiteBase;\n\n"
            + "/**\n"
            + " * Runs every test case in the recorded keyword script, one TestNG test per test case. Generated by\n"
            + " * RecorderCli; a newly recorded test case is picked up automatically, with no Java to write.\n"
            + " */\n"
            + "public class " + className + " extends KeywordScriptSuiteBase {\n\n"
            + "    @Override\n"
            + "    protected String objectRepository() {\n"
            + "        return \"" + objectRepoName + "\";\n"
            + "    }\n\n"
            + "    @Override\n"
            + "    protected String scriptPath() {\n"
            + "        return \"" + scriptPath + "\";\n"
            + "    }\n"
            + "}\n";
    }

    static String suiteSource(String site, String pkg, String className) {
        return "<!DOCTYPE suite SYSTEM \"https://testng.org/testng-1.0.dtd\">\n"
            + "<!-- Runs the recorded keyword test cases for " + site + ". Generated by RecorderCli.\n"
            + "     mvn test -Dsite=" + site + " -DsuiteXmlFile=testng-suites/" + site + "-recorded.xml -->\n"
            + "<suite name=\"" + site + " Recorded Keyword Suite\" parallel=\"classes\" thread-count=\"3\">\n\n"
            + "  <listeners>\n"
            + "    <listener class-name=\"com.automation.sites.listeners.RetryListener\"/>\n"
            + "  </listeners>\n\n"
            + "  <test name=\"" + site + " Recorded Keyword Tests\" preserve-order=\"true\">\n"
            + "    <classes>\n"
            + "      <class name=\"com.automation.sites." + pkg + ".tests." + className + "\"/>\n"
            + "    </classes>\n"
            + "  </test>\n\n"
            + "</suite>\n";
    }
}
